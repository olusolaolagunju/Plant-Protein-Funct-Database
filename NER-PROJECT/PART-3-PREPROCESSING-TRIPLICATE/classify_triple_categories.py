    "          f\"({counts.get('uncategorized', 0) / len(df) * 100:.1f}%)\")\n",
    "\n",
    "    out_path = in_path.parent / f\"{in_path.stem}_categorized.xlsx\"\n",
    "    df.to_excel(out_path, index=False)\n",
    "    print(f\"\\nCategorized triples -> {out_path}\")\n",
    "\n",
    "    sample_rows = []\n",
    "    for cat in df[\"category\"].unique():\n",
    "        sample_rows.append(df[df[\"category\"] == cat].head(5))\n",
    "    sample_df = pd.concat(sample_rows, ignore_index=True)\n",
    "    sample_path = in_path.parent / f\"{in_path.stem}_category_samples.xlsx\"\n",
    "    sample_df.to_excel(sample_path, index=False)\n",
    "    print(f\"Spot-check samples (5 per category) -> {sample_path}\")\n",
    "\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    main()"
